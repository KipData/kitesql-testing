#!/usr/bin/env python3
"""Convert the SQLite sqllogictest corpus into scripts KiteSQL can run.

Only what KiteSQL cannot run is rewritten; queries and expected results are kept as is:
- conditional records (`onlyif`/`skipif`) are resolved for the upstream SQLite baseline and removed, and a
  conditional `halt` either truncates the file or is dropped;
- a table without a primary key gets a leading `pk INTEGER PRIMARY KEY` column, filled with an
  increasing value by every INSERT;
- `SELECT *` over such a table is expanded to its original columns;
- bare `DROP INDEX` names gain an `ON table` clause from the preceding CREATE INDEX;
- SQLite `IN table` shorthand expands to a subquery over that table's original columns.

Usage: scripts/convert.py [FILE ...]   (FILE is relative to the upstream `test/` directory;
defaults to the list in scripts/files.txt)
"""
import argparse
import re
import urllib.request
from pathlib import Path

UPSTREAM = "https://raw.githubusercontent.com/gregrahn/sqllogictest"
COMMIT = "c67f97bf3ca7e590d12e073408bcacaf2ff0f3a0"
ENGINE = "sqlite"
ROOT = Path(__file__).resolve().parent.parent
HEADER = """# Generated by scripts/convert.py from sqllogictest test/{path} @ {commit}

control resultmode valuewise

"""

COND_RE = re.compile(r"^(onlyif|skipif)\s+(\S+)")
CREATE_RE = re.compile(r"^\s*CREATE\s+TABLE\s+(\w+)\s*\((.*)\)\s*$", re.I | re.S)
DROP_RE = re.compile(r"^\s*DROP\s+TABLE\s+(?:IF\s+EXISTS\s+)?(\w+)", re.I)
CREATE_INDEX_RE = re.compile(r"^\s*CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)\s+ON\s+(\w+)\b", re.I)
DROP_INDEX_RE = re.compile(r"^(\s*DROP\s+INDEX\s+(?:IF\s+EXISTS\s+)?)(\w+)(\s*;?\s*)$", re.I)
INSERT_RE = re.compile(r"^(\s*INSERT\s+INTO\s+(\w+)\s*)(\(([^)]*)\))?(\s*VALUES\s*)(.*)$", re.I | re.S)
STAR_RE = re.compile(r"(\bSELECT\s+(?:ALL\s+|DISTINCT\s+)?)\*\s+FROM\s+(\w+)\b(?!\s*,)", re.I)
INSERT_SELECT_RE = re.compile(r"^(\s*INSERT\s+INTO\s+(\w+)\s*)SELECT\s+\*\s+FROM\s+(\w+)\s*;?\s*$", re.I)
EMPTY_IN_RE = re.compile(r"\bIN\s*\(\s*\)", re.I)
TABLE_IN_RE = re.compile(r"""'(?:''|[^'])*'|"(?:""|[^"])*"|\bIN\s+(\w+)\b(?!\s*\()""", re.I)
ANY_STAR_RE = re.compile(r"SELECT\s+(?:ALL\s+|DISTINCT\s+)?\*|\b\w+\.\*", re.I)
CONSTRAINT_RE = re.compile(r"(PRIMARY|UNIQUE|CHECK|FOREIGN|CONSTRAINT)\b", re.I)


def split_top(s):
    """Split on commas outside parentheses and quotes."""
    parts, cur, depth, quote = [], [], 0, None
    for ch in s:
        if quote:
            quote = None if ch == quote else quote
        elif ch in "'\"":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append("".join(cur))
            cur = []
            continue
        cur.append(ch)
    parts.append("".join(cur))
    return [p.strip() for p in parts if p.strip()]


def tuple_starts(values):
    """Offsets of the `(` opening each top-level tuple of a VALUES list."""
    starts, depth, quote = [], 0, None
    for i, ch in enumerate(values):
        if quote:
            quote = None if ch == quote else quote
        elif ch in "'\"":
            quote = ch
        elif ch == "(":
            if depth == 0:
                starts.append(i)
            depth += 1
        elif ch == ")":
            depth -= 1
    return starts


def rewrite(sql, kind, tables, indexes, stats):
    if m := CREATE_INDEX_RE.match(sql):
        indexes[m.group(1).lower()] = m.group(2)
    if m := DROP_INDEX_RE.match(sql):
        table = indexes.get(m.group(2).lower())
        if table is not None:
            # Retain ownership for repeated DROP tests; never invent a table for an unknown index.
            return f"{m.group(1)}{m.group(2)} ON {table}{m.group(3)}"
    if m := CREATE_RE.match(sql):
        defs = split_top(m.group(2))
        cols = [d.split()[0] for d in defs if not CONSTRAINT_RE.match(d)]
        has_pk = bool(re.search(r"PRIMARY\s+KEY", m.group(2), re.I))
        tables[m.group(1).lower()] = {"cols": cols, "pk": None if has_pk else 0, "rows": 0}
        # SQLite INTEGER arithmetic is 64-bit; do not widen KiteSQL's declared INT semantics.
        defs = [re.sub(r"\bINTEGER\b", "BIGINT", d, flags=re.I)
                if not re.search(r"PRIMARY\s+KEY", d, re.I) else d for d in defs]
        sql = sql[:sql.index("(") + 1] + ", ".join(defs) + ")"
        if has_pk:
            return sql
        stats["tables"] += 1
        i = sql.index("(") + 1
        pk = "\n  pk INTEGER PRIMARY KEY," if sql[i:i + 1] == "\n" else "pk INTEGER PRIMARY KEY, "
        return sql[:i] + pk + sql[i:]
    if m := DROP_RE.match(sql):
        tables.pop(m.group(1).lower(), None)
        return sql
    injected = [name for name, t in tables.items() if t["pk"] is not None]
    if m := INSERT_SELECT_RE.match(sql):
        target = tables.get(m.group(2).lower())
        source = tables.get(m.group(3).lower())
        if target and source:
            values = ", ".join(source["cols"])
            if target["pk"] is not None:
                if source["pk"] is None:
                    raise ValueError("synthetic PK INSERT SELECT requires an injected source PK: " + sql)
                values = f"pk + {target['pk']}, {values}"
                target["pk"] += source["rows"]
            target["rows"] += source["rows"]
            stats["inserts"] += 1
            return f"{m.group(1)}SELECT {values} FROM {m.group(3)}"
    if m := INSERT_RE.match(sql):
        if m.group(2).lower() in tables:
            tables[m.group(2).lower()]["rows"] += len(tuple_starts(m.group(6)))
    if (m := INSERT_RE.match(sql)) and m.group(2).lower() in injected:
        t, values = tables[m.group(2).lower()], m.group(6)
        starts = tuple_starts(values)
        for k, s in reversed(list(enumerate(starts))):
            values = f"{values[:s + 1]}{t['pk'] + k}, {values[s + 1:]}"
        t["pk"] += len(starts)
        stats["inserts"] += 1
        cols = f"(pk, {m.group(4)})" if m.group(3) else ""
        return f"{m.group(1)}{cols}{m.group(5)}{values}"
    def expand_star(match):
        name = match.group(2).lower()
        if name not in injected:
            return match.group(0)
        stats["stars"] += 1
        cols = ", ".join(tables[name]["cols"])
        return f"{match.group(1)}{cols} FROM {match.group(2)}"
    sql = STAR_RE.sub(expand_star, sql)
    # SQLite accepts an empty IN list; a zero-row RHS has the same NULL semantics.
    sql = EMPTY_IN_RE.sub("IN (SELECT NULL WHERE false)", sql)
    def expand_table_in(match):
        name = match.group(1)
        if name is None:
            return match.group(0)
        table = tables.get(name.lower())
        if table is None:
            return match.group(0)
        return f"IN (SELECT {', '.join(table['cols'])} FROM {name})"
    sql = TABLE_IN_RE.sub(expand_table_in, sql)
    mentions = injected and re.search(r"\b(" + "|".join(injected) + r")\b", sql, re.I)
    if mentions and (ANY_STAR_RE.search(sql) or re.match(r"\s*INSERT\b", sql, re.I)):
        stats["warnings"].append(" ".join(sql.split())[:120])
    return sql


def convert(text, stats):
    tables, indexes, out = {}, {}, []
    for block in re.split(r"\n[ \t]*\n", text.strip("\n")):
        lines = [line.rstrip() for line in block.split("\n")]
        keep, conds, rest = [], [], []
        for line in lines:
            if not rest and (m := COND_RE.match(line)):
                conds.append((m.group(1), m.group(2).lower()))
            elif not rest and line.startswith("#"):
                keep.append(line)
            else:
                rest.append(line)
        runs = all((kind == "onlyif") == (engine == ENGINE) for kind, engine in conds)
        while rest and not rest[0].strip():
            rest.pop(0)
        if not rest:
            if keep:
                out.append("\n".join(keep))
            continue
        head = rest[0].split()[0]
        if head == "halt" and runs:
            stats["halted"] = True
            break
        if head == "halt" or not runs:
            stats["dropped"] += 1
            continue
        if head in ("statement", "query"):
            end = rest.index("----") if "----" in rest else len(rest)
            sql = rewrite("\n".join(rest[1:end]), head, tables, indexes, stats)
            rest = [rest[0], *sql.split("\n"), *rest[end:]]
        out.append("\n".join(keep + rest))
    return "\n\n".join(out)


def fetch(path, cache):
    local = cache / COMMIT / path
    if not local.exists():
        local.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(f"{UPSTREAM}/{COMMIT}/test/{path}") as resp:
            local.write_bytes(resp.read())
    return local.read_text()


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("files", nargs="*")
    parser.add_argument("--list", type=Path, default=ROOT / "scripts" / "files.txt")
    parser.add_argument("--cache", type=Path, default=ROOT / ".cache")
    parser.add_argument("--out", type=Path, default=ROOT / "data" / "sqlite")
    args = parser.parse_args()
    files = args.files or [
        line.strip() for line in args.list.read_text().splitlines()
        if line.strip() and not line.startswith("#")
    ]
    for path in files:
        stats = {"dropped": 0, "tables": 0, "inserts": 0, "stars": 0, "halted": False, "warnings": []}
        body = convert(fetch(path, args.cache), stats)
        dest = args.out / Path(path).with_suffix(".slt")
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(HEADER.format(path=path, commit=COMMIT) + body + "\n")
        print(f"{path}: pk tables={stats['tables']} inserts={stats['inserts']} select*={stats['stars']} "
              f"dropped={stats['dropped']} halted={stats['halted']}")
        for warning in stats["warnings"]:
            print(f"  warning: {warning}")


if __name__ == "__main__":
    main()
